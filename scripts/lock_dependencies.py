"""Pin installed dependency closure separately for runtime and local tests."""
from importlib.metadata import distribution
from pathlib import Path
from packaging.requirements import Requirement
from packaging.utils import canonicalize_name

ROOT = Path(__file__).resolve().parents[1]


def closure(names):
    found = {}
    def visit(name):
        key = canonicalize_name(name)
        if key in found:
            return
        dist = distribution(name)
        found[key] = f"{dist.metadata['Name']}=={dist.version}"
        for item in dist.requires or []:
            req = Requirement(item)
            if req.marker is None or req.marker.evaluate({"extra": ""}):
                visit(req.name)
    for name in names:
        visit(name)
    return found


def write_manifests(runtime, dev, root=ROOT):
    # Vercel discovers requirements.txt directly. Keep it self-contained rather
    # than relying on its parser to resolve a nonstandard .lock include.
    content = "# Verified runtime dependency closure. Generated by scripts/lock_dependencies.py\n" + "\n".join(v for _, v in sorted(runtime.items())) + "\n"
    for name in ["requirements.lock", "requirements.txt"]:
        (root / name).write_text(content, encoding="utf-8", newline="\n")
    (root / "requirements-dev.lock").write_text("-r requirements.lock\n" + "\n".join(v for k,v in sorted(dev.items()) if k not in runtime) + "\n", encoding="utf-8", newline="\n")


def main():
    runtime = closure(["fastapi", "uvicorn", "langgraph", "sqlglot", "httpx", "python-dotenv"])
    dev = closure(["pytest", "pytest-asyncio"])
    # Colorama is Windows-only; make the lock portable for Linux/Docker/Vercel.
    for group in [runtime, dev]:
        if "colorama" in group:
            group["colorama"] += '; sys_platform == "win32"'
    write_manifests(runtime, dev)
    print(f"Pinned {len(runtime)} runtime and {len(dev)} test dependency entries; synchronized requirements.txt")


if __name__ == "__main__":
    main()
